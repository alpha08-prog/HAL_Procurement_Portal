"""Interactive, decision-based driver for the HAL note cascade.

Walks cascade.NODES one decision at a time. At every node the sheet names exactly
one agency that may raise the note ("Note Can only be Generated by"), so the CLI
enforces it: acting out of turn is refused, and the file must be handed over to
the other agency first. Whatever note you pick is generated for real through
pipeline.run_stage() -- same deterministic formats, same carry-forward, same SLM.

Run it from run.py (default) or directly:
    conda run -n hal python ai/interactive.py [--agency Indenting|Tendering]
"""

